// The node:sqlite half of the bun:sqlite probe; bun.ts does the same steps. Usage: node node.mjs <db file>
import { DatabaseSync } from 'node:sqlite';
const file = process.argv[2];
const out = (k, v) => console.log(JSON.stringify([k, v === undefined ? null : v]));
const err = (k, f) => { try { out(k, f()); } catch (e) { out(k, 'ERR ' + e.message); } };

let db = new DatabaseSync(file);
out('wal', db.prepare('PRAGMA journal_mode = WAL').get());
db.exec('PRAGMA foreign_keys = ON');
out('fk', db.prepare('PRAGMA foreign_keys').get());
out('uv0', db.prepare('PRAGMA user_version').get());
db.exec(`CREATE TABLE videos (videoId TEXT PRIMARY KEY, title TEXT, segment_count INTEGER NOT NULL DEFAULT 0);
CREATE TABLE tags (videoId TEXT NOT NULL REFERENCES videos(videoId) ON DELETE CASCADE, tag TEXT NOT NULL, UNIQUE(videoId, tag));
CREATE VIRTUAL TABLE videos_fts USING fts5(videoId UNINDEXED, title, transcript_text, digest);`);
out('cols', db.prepare('PRAGMA table_info(videos)').all());
const ins = db.prepare('INSERT INTO videos (videoId, title, segment_count) VALUES (?, ?, ?)');
out('ins1', ins.run('a', 'Straße café 🎉', 3));
out('ins2', ins.run('b', null, 0));
out('dup', (() => { try { return ins.run('a', 'x', 1); } catch (e) { return 'ERR ' + e.message; } })());
const rid = db.prepare('SELECT rowid FROM videos WHERE videoId = ?');
const fts = db.prepare('INSERT INTO videos_fts (rowid, videoId, title, transcript_text, digest) VALUES (?, ?, ?, ?, ?)');
const long = Array.from({ length: 60 }, (_, i) => 'word' + i).join(' ') + ' machine learning ' + Array.from({ length: 60 }, (_, i) => 'tail' + i).join(' ');
out('fts1', fts.run(rid.get('a').rowid, 'a', 'Straße café 🎉', long, '## TL;DR\n\nlearning is fun'));
out('fts2', fts.run(rid.get('b').rowid, 'b', null, 'nothing here', null));
const search = db.prepare(`SELECT f.videoId, v.title, snippet(videos_fts, -1, '', '', '…', 24) AS snippet
  FROM videos_fts f JOIN videos v ON v.videoId = f.videoId WHERE videos_fts MATCH ? ORDER BY rank LIMIT ?`);
out('search', search.all('learning', 20));
out('searchUnicode', search.all('café', 20));
out('searchNone', search.all('zzz', 20));
err('searchBad', () => search.all('"unterminated', 20));
err('searchBad2', () => search.all('AND OR', 20));
out('none', db.prepare('SELECT * FROM videos WHERE videoId = ?').get('nope'));
db.exec("INSERT INTO tags VALUES ('a', 'ai'), ('a', 'ml')");
db.exec('BEGIN');
ins.run('c', 'rolled back', 1);
db.exec('ROLLBACK');
out('afterRollback', db.prepare('SELECT videoId FROM videos ORDER BY videoId').all());
db.exec('BEGIN');
db.exec("DELETE FROM videos_fts WHERE rowid = (SELECT rowid FROM videos WHERE videoId = 'a')");
db.exec("DELETE FROM videos WHERE videoId = 'a'");
db.exec('COMMIT');
out('cascade', db.prepare('SELECT count(*) AS n FROM tags').get());
out('ftsLeft', db.prepare('SELECT videoId FROM videos_fts').all());
db.exec('PRAGMA user_version = 2');
out('uv1', db.prepare('PRAGMA user_version').get());
db.close();
db = new DatabaseSync(file);
out('reopenUv', db.prepare('PRAGMA user_version').get());
out('reopenWal', db.prepare('PRAGMA journal_mode').get());
out('reopenRows', db.prepare('SELECT videoId, title, segment_count FROM videos').all());
db.close();
